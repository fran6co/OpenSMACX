// `_itoa` (the CRT converter, source-decorated to `__itoa` at link time) has
// no recorded prototype in the catalogue, so `mizuchi_declfix` leaves the
// scaffold's fallback nullary - `extern "C" int __cdecl _itoa();` above -
// exactly as unsettled as the read/write/close trio it documents. Declaring
// the real 3-arg signature under THAT name is `C2733: second C linkage`;
// this project's own fix (see the preserved ?say_chassis@@ unit) is a
// differently-spelled extern with the right arity. The relocation target is
// masked by the comparison, so the exact spelling of the callee's name does
// not matter - only the calling convention and the pushed arguments do.
extern "C" char *itoa(int, char *, int);
// `strcat`/`strlen` are CL built-in intrinsics by name; left alone, CL
// inlines a byte-copy/repne-scasb loop at every call site instead of
// emitting a `call`, and the body comes out ~120 bytes bigger. `#pragma
// function` forces a real call, matching the original's call-based shape.
#pragma function(strcat)
#pragma function(strlen)

void Datalink::set_cat_chassis() {
    char *self = reinterpret_cast<char *>(this);

    int chassis_id = 0x9c40;
    char *rec = reinterpret_cast<char *>(&g_0094a330);
    do {
        if (*reinterpret_cast<short *>(rec + 0x8e) >= -1) {
            *reinterpret_cast<char *>(g_009b86a0) = 0;
            char *name = reinterpret_cast<char *>(
                reinterpret_cast<Strings *>(g_009b90d8)->get(
                    *reinterpret_cast<int *>(rec)));
            strcat(reinterpret_cast<char *>(g_009b86a0), name);
            if (*g_009a64c0 & 0x1000) {
                strcat(reinterpret_cast<char *>(g_009b86a0),
                       reinterpret_cast<char *>(g_006832d0));
                char buffer[0x50];
                itoa(chassis_id, buffer, 10);
                strcat(reinterpret_cast<char *>(g_009b86a0), buffer);
            }
            reinterpret_cast<ListBox *>(self + 0xf628)->item(
                reinterpret_cast<char *>(g_009b86a0), chassis_id);
        }
        rec += 0x90;
    } while (++chassis_id - 0x9c40 < 9);

    RECT rect = *reinterpret_cast<RECT *>(self + 0x103d4);
    Buffer *buf = &buffer_;
    buf->box_sprite(&rect, reinterpret_cast<BoxSpriteParams *>(g_0078d618));
    rect.left += 3;
    rect.right -= 3;
    rect.top += 3;
    rect.bottom -= 3;
    buf->set_text_color(0xe0, -1, 1, 1);
    buf->set_font(reinterpret_cast<Font *>(self + 0x101cc), 0, 0, 0);

    int base = *g_009b90f8;
    int val = *reinterpret_cast<int *>(base + 0xb30);
    char *s = reinterpret_cast<char *>(
        reinterpret_cast<Strings *>(g_009b90d8)->get(val));
    if (s != 0) {
        buf->write_cent_l(s, &rect, strlen(s));
    }

    reinterpret_cast<GraphicWin *>(self)->soft_update(
        reinterpret_cast<RECT *>(self + 0x103d4));
}
