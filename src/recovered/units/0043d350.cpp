// BYTE_EXACT. `clear_bubble_text` is called twice with NO stack push
// and no `mov ecx,X` between the two `call`s - the mangled name's
// `SAXXZ` (not the usual thiscall `QAEXXZ`) IS a static member
// (verified: declaring it `static` on Win, called via `Win::`,
// removes an otherwise-forced `mov ecx,esi` reload between the two
// calls and matches byte-for-byte). `check`'s two int* out-params
// are at `[esi+0x11d44]` (Spot embedded far past DesignWin's own
// members - true regardless of what class_layouts currently has
// `spot_` at); only the first (`local4`) is ever read back. The
// second store target for `draw_flash` is `this - 0xa14`, not
// `this` - on_iface_mouse_move's own `this` is 0xa14 bytes into
// whatever owns `draw_flash`, not that object itself, i.e. this is
// reached through a secondary vtable and needs the adjustment back.
// The `newVal` local (not reusing `local4`/writing the literal into
// its slot) matters: `local4`'s address escapes to `check()`, so
// assigning through it directly forces VC6 to spill every write back
// to its stack slot even where the original just keeps the value in
// a register (ruled out - one extra `mov [ebp-4],eax` between the
// `cmp` and `je` that the original does not have).
void DesignWin::on_iface_mouse_move(int a1, int a2) {
    char *self = reinterpret_cast<char *>(this);
    Win::clear_bubble_text();
    Win::clear_bubble_text();
    int local4;
    int local8;
    int result = reinterpret_cast<Spot *>(self + 0x11d44)->check(a1, a2, &local4, &local8);
    int newVal;
    if (result != -1) {
        newVal = local4;
        if (*reinterpret_cast<int *>(self + 0x2cc) == newVal) {
            return;
        }
    } else {
        newVal = 0x3f;
        if (*reinterpret_cast<int *>(self + 0x2cc) == newVal) {
            return;
        }
    }
    *reinterpret_cast<int *>(self + 0x2cc) = newVal;
    reinterpret_cast<DesignWin *>(self - 0xa14)->draw_flash();
}

