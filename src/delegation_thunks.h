/*
 * Guarded delegation thunks - was generated by
 * tools/generate_delegation_thunks.py, WHICH NO LONGER EXISTS: commit 271114cf retired
 * eleven bulk generators as "9,262 lines that nobody could run". EDIT THIS
 * FILE DIRECTLY. The old instruction to edit the generator instead survived
 * the generator by months and told every reader not to touch this file in the
 * only way it can now be touched.
 *
 * One shape, 59 times over: read a member object pointer, answer a constant
 * when it is absent, otherwise forward the arguments through a slot of that
 * member's OWN vtable. The four numbers that differ per function - the member
 * offset, the slot, the forwarded argument count and the absent-member
 * constant - are read from the bytes of each function and are kept as inline
 * literals here so a mutation sweep has something to perturb.
 *
 * Most rows are free redirects over opaque storage rather than methods;
 * the classes involved there are still unmodelled. The 32 Midi rows became
 * real `Midi::` methods on 2026-08-23 - their delegate is modelled as
 * `MidiDelegate` in midi.h with virtuals at the image's own
 * slot order - so this header declares none of them any more.
 */

// The delegate is entered on the MEMBER, not on the thunk's
// own object, so every one of these is __thiscall with the
// member as its receiver.
