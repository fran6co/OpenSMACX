#include <cassert>
#include <cstdint>

struct Scroll {};

struct Win {
    virtual ~Win() {}
    virtual Scroll *on_scroll_create() { return 0; }
    virtual Scroll *on_scroll_delete(Scroll *value) { return value; }
    virtual Scroll *on_listbox_scroll_create() { return 0; }
    virtual Scroll *on_listbox_scroll_delete(Scroll *value) { return value; }
};

struct Recipient : Win {
    int create_calls;
    int delete_calls;
    Scroll *last_scroll;
    Scroll *create_result;
    Scroll *delete_result;

    Recipient() : create_calls(0), delete_calls(0), last_scroll(0),
                  create_result(0), delete_result(0) {}
    Scroll *on_listbox_scroll_create() override {
        ++create_calls;
        return create_result;
    }
    Scroll *on_listbox_scroll_delete(Scroll *value) override {
        ++delete_calls;
        last_scroll = value;
        return delete_result;
    }
};

struct ListBox : Win {
    unsigned int val_20_;
    Win *val_31_;

    ListBox() : val_20_(0), val_31_(0) {}
    Scroll *on_scroll_create() override;
    Scroll *on_scroll_delete(Scroll *scroll) override;
};

// This include is generated by test_listbox_scroll_interface_actual_source.py from the actual source-owned
// ListBox method bodies. Only pointer-to-int conversions are adapted for an
// LP64 host; the target is 32-bit and those original casts retain low EAX bits.
#include "actual_listbox_methods.inc"

int main() {
    ListBox list;
    Recipient recipient;
    Scroll vertical;
    Scroll horizontal;

    // Disabled flag skips both virtual forwards and returns the original
    // default values/pointer without touching the recipient.
    list.val_31_ = &recipient;
    assert(list.on_scroll_create() == 0);
    assert(list.on_scroll_delete(&vertical) == &vertical);
    assert(recipient.create_calls == 0 && recipient.delete_calls == 0);

    // Flag set but null recipient preserves the distinct fallback values.
    list.val_20_ = 0x40;
    list.val_31_ = 0;
    assert(list.on_scroll_create() == 0);
    assert(list.on_scroll_delete(&horizontal) == &horizontal);

    // With both guards satisfied, slot 8's value and slot 9's exact argument
    // and result flow through unchanged.
    list.val_31_ = &recipient;
    Scroll created;
    Scroll replacement;
    recipient.create_result = &created;
    recipient.delete_result = &replacement;
    assert(list.on_scroll_create() == &created);
    assert(list.on_scroll_delete(&vertical) == &replacement);
    assert(recipient.create_calls == 1);
    assert(recipient.delete_calls == 1);
    assert(recipient.last_scroll == &vertical);

    // The extracted owner body preserves the recipient's return bits.
    recipient.delete_result = 0;
    assert(list.on_scroll_delete(&horizontal) == 0);
    assert(recipient.last_scroll == &horizontal);
    return 0;
}
