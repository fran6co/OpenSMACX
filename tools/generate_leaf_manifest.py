#!/usr/bin/env python3
"""Derive the leaf suite's case manifest from the family sources.

The manifest tells the run-time registry how many cases each family file is
supposed to register.  It used to be a checked-in header that every author had
to bump by hand, which made it the one file two independent recoveries in
different families always collided on.  Counting the ``LEAF_CASE(`` lines here
removes that edit entirely.

The counts must NOT be derived from the CMake source list they are meant to
police.  If a family file drops out of that list, it has to disappear from the
build while remaining in the manifest, so the registry notices the missing
cases.  CMake therefore feeds this script an independent glob of
``tests/leaf/*_tests.cpp`` and fails at configure time if the glob and the
explicit list disagree; see CMakeLists.txt.
"""

import argparse
import os
import re
import sys

# A registration only counts when LEAF_CASE starts the line.  Anything indented
# is inside a conditional, a comment block or a string, and the compiler may
# well not register it; the run-time count check exists to catch exactly that
# disagreement, so this pattern stays deliberately literal.
LEAF_CASE_RE = re.compile(r"^LEAF_CASE\(", re.MULTILINE)

LEAF_FAMILY_RE = re.compile(
    r"^#define\s+LEAF_FAMILY\s+\"([A-Za-z0-9_]+)\"\s*$", re.MULTILINE)

FILE_SUFFIX = "_tests.cpp"

HEADER = """\
// GENERATED by tools/generate_leaf_manifest.py - do not edit, do not check in.
//
// How many cases each family file is expected to register, counted from the
// `LEAF_CASE(` lines in tests/leaf/*_tests.cpp at build time.
//
// main() checks these at RUN TIME.  A family whose file drops out of the CMake
// source list, or whose static initialisers are discarded, or whose LEAF_CASE
// line is present in the text but cannot register (an `#if 0`, say), registers
// fewer cases than its line here claims, and the run fails loudly instead of
// quietly losing coverage.
//
// The counts come from a glob of the directory, not from the CMake source
// list, precisely so that removing a file from that list cannot remove it from
// both sides of the comparison.  CMake fails at configure time if the glob and
// the list disagree in either direction.
//
// LEAF_FAMILY_COUNT(<family>, <cases>)
"""


class ManifestError(Exception):
    pass


def family_of(path, text):
    """The family name the file registers under, cross-checked against its name."""
    matches = LEAF_FAMILY_RE.findall(text)
    if not matches:
        raise ManifestError(
            f"{path}: no `#define LEAF_FAMILY \"...\"` line; every family file "
            f"must declare the name its cases register under")
    if len(set(matches)) > 1:
        raise ManifestError(
            f"{path}: {len(set(matches))} different LEAF_FAMILY names "
            f"({', '.join(sorted(set(matches)))}); a file registers under one")
    family = matches[0]

    base = os.path.basename(path)
    if not base.endswith(FILE_SUFFIX):
        raise ManifestError(
            f"{path}: a family file must be named <family>{FILE_SUFFIX}")
    from_name = base[: -len(FILE_SUFFIX)]
    if from_name != family:
        raise ManifestError(
            f"{path}: file name says family {from_name!r} but LEAF_FAMILY says "
            f"{family!r}; the two must agree or the manifest names a family "
            f"nothing registers under")
    return family


def rows_for(paths):
    """[(family, count)] sorted by family, one row per source file."""
    rows = []
    seen = {}
    for path in paths:
        with open(path, "r", encoding="utf-8") as handle:
            text = handle.read()
        family = family_of(path, text)
        if family in seen:
            raise ManifestError(
                f"{path}: family {family!r} is already registered by "
                f"{seen[family]}; two files cannot share a family name")
        seen[family] = path
        rows.append((family, len(LEAF_CASE_RE.findall(text))))
    rows.sort()
    return rows


def render(rows):
    body = "".join(f"LEAF_FAMILY_COUNT({family}, {count})\n"
                   for family, count in rows)
    return HEADER + body


def write_if_changed(path, text):
    """Avoid a needless recompile of the whole harness on an unrelated edit."""
    try:
        with open(path, "r", encoding="utf-8") as handle:
            if handle.read() == text:
                return False
    except OSError:
        pass
    directory = os.path.dirname(path)
    if directory:
        os.makedirs(directory, exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(text)
    return True


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True,
                        help="header to write")
    parser.add_argument("sources", nargs="+",
                        help="tests/leaf/<family>_tests.cpp files")
    args = parser.parse_args(argv)

    try:
        rows = rows_for(args.sources)
    except ManifestError as error:
        print(f"generate_leaf_manifest: {error}", file=sys.stderr)
        return 2

    write_if_changed(args.output, render(rows))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
